"""D1 for the v3 judge, the DIALOGUE part: three constructed negatives on synthetic dialogues.

The v3 judge is a cross-encoder P(supported | source, claim) that must treat «says more than the source»
as NOT supported. The gate asks it one claim at a time: the memory goes through `decomponi()` first, and
the verdict is the weakest claim. So D1 builds each memory from atomic claims whose label the generator
knows, runs `decomponi()`, and gives every output unit the label of the weakest atomic claim it contains:
the judge is trained on the same unit, and with the same rule, it is asked about.

No model and no external data: names, places and sentences are templates written here. Deterministic
with the seed. Languages: English, Italian, French and Spanish (coordinators «and», «e/ed», «et», «y»;
the French passé composé is left out, because «a» cannot be a finite verb in a list shared with English).

Pair types (field `tipo`):
  sostenuta        the cited turn -> one of its facts, literal, paraphrased or with a   label 1
                   small inference («adopted a cat» -> «has a new cat»)
  altro_turno      the cited turn -> a unit that comes from ANOTHER turn of the speaker label 0
  parlante         B's turn (B names A) -> the same fact attributed to A                label 0
  fonte_turno      the turn with the pronoun («I loved it!») -> the fact, referent named label 0
  fonte_finestra   the window that names the referent -> the same fact                  label 1

A small inference enters only if it holds for EVERY value of its slots: «signed up for X» -> «has a
spot at X» stays out, because who signs up can end on a waiting list.

Fields per row: id, dialogo, lingua, tipo, fonte, memoria, claim, etichetta, unita_nella_memoria (how
many units the memory became), indice_unita (which unit the claim is, from 0), generatore, seme. The
rows go through `d1_campi.controlla()` before they are written.

Run from the root of the checkout, with the `verimem` of this checkout:
    python benchmark/judge_v3/d1_dialoghi.py --dialoghi 60 --seme 20260930 \
        --uscita benchmark/judge_v3/d1-dialoghi.jsonl --campione 200
The full jsonl is regenerated by the script and not committed; its sha256 goes in the data card, and the
200-row sample sits next to this file.
"""
