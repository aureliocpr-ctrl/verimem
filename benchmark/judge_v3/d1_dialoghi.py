def _riempi(modello: str, voci: dict, S: str = "") -> str:
    return modello.format(S=S, **voci)


def _con_forma_a(voci: dict, t: dict) -> dict:
    """«a» + articolo per l'evento scelto (solo italiano); in inglese la chiave non serve."""
    voci = dict(voci)
    voci["evento_a"] = t.get("eventi_a", {}).get(voci["evento"], voci["evento"])
    return voci


def _voci(rng: random.Random, t: dict) -> dict:
    return {"luogo": rng.choice(t["luoghi"]), "quando": rng.choice(t["quando"]),
            "citta": rng.choice(t["citta"]), "mese": rng.choice(t["mesi"]),
            "cosa": rng.choice(t["cose"]), "evento": rng.choice(t["eventi"]),
            "azienda": rng.choice(t["aziende"]), "animale": rng.choice(t["animali"])}


def dialogo(rng: random.Random, lingua: str, n: int) -> dict:
    """Un dialogo sintetico fra A e B, con i fatti di ciascun turno e la terna del pronome."""
    t = LINGUE[lingua]
    A, B = rng.sample(t["nomi"], 2)
    turni = []   # (parlante, testo, claim del fatto o None)
    corpi_usati: set[str] = set()
    voci_turno_0: dict = {}
    for i in range(4):
        parlante = A if i % 2 == 0 else B
        # fatti DIVERSI fra i turni: se il turno 2 ripetesse il turno 0, la stessa frase avrebbe
        # etichetta 1 (la dice il turno citato) e 0 (viene da un altro turno) nella stessa memoria
        while True:
            voci = _con_forma_a(_voci(rng, t), t)
            if i == 2:
                # stesso luogo e stesso evento del turno 0: l'omissione realistica (pilota, p068)
                # parla dello stesso argomento, e non si riconosce dalle parole in comune
                voci.update({k: voci_turno_0[k] for k in ("luogo", "evento", "evento_a")})
            prima, varianti = rng.choice(t["fatti"])
            # la distinzione fra turni guarda TUTTE le varianti: l'inferenza piccola lascia cadere il
            # tempo, e «adopted a parrot on Friday» e «... yesterday» darebbero lo stesso «has a new parrot»
            corpi = {_riempi(v, voci, "") for v in varianti}
            terza = rng.choice(varianti)
            # il turno 2 riusa il luogo del turno 0 ma non il tempo: «met my cousin at the park last week»
            # implica «went to the park last week», e il negativo dell'altro turno sarebbe sostenuto
            stesso_tempo = i == 2 and "{quando}" in prima and voci["quando"] == voci_turno_0["quando"]
            if not corpi & corpi_usati and not stesso_tempo:
                corpi_usati |= corpi
                if i == 0:
                    voci_turno_0 = voci
                break
        testo = _riempi(prima, voci)
        if i == 1:
            # B chiama A per nome: nel negativo del parlante scambiato il nome di A c'e' nella fonte,
            # quindi il giudice deve attribuire per PARLANTE, non per presenza del nome
            testo = f"{A}, {_minuscola_iniziale(testo)}"
        turni.append((parlante, testo, _riempi(terza, voci, parlante)))
    # la terna del pronome: A nomina l'evento, B chiede, A risponde col pronome
    voci = _con_forma_a(_voci(rng, t), t)
    turni.append((A, _riempi(t["evento_andato"][0], voci), _riempi(t["evento_andato"][1], voci, A)))
    turni.append((B, rng.choice(t["domande"]), None))
    frasi, claim_del_pronome = t["pronome"]
    turni.append((A, rng.choice(frasi), _riempi(claim_del_pronome, voci, A)))
    return {"id": f"{lingua}-{n:04d}", "lingua": lingua, "A": A, "B": B, "turni": turni}


def _minuscola_iniziale(testo: str) -> str:
    """«Ho visitato» -> «ho visitato»; il pronome inglese «I» resta maiuscolo."""
    if testo.startswith(("I ", "I'")):
        return testo
    return testo[:1].lower() + testo[1:]


def _riga(parlante: str, testo: str) -> str:
    return f"{parlante}: {testo}"


GENERATORE = "d1_dialoghi@6"


def coppie(d: dict, seme: int) -> list[dict]:
    t = LINGUE[d["lingua"]]
    turni, A = d["turni"], d["A"]
    out = []

    def aggiungi(tipo, fonte, memoria, unita, etichetta, quante, indice=0):
        out.append({"id": f"{d['id']}-{len(out):02d}", "dialogo": d["id"], "lingua": d["lingua"],
                    "tipo": tipo, "fonte": fonte, "memoria": memoria, "claim": unita,
                    "etichetta": etichetta, "unita_nella_memoria": quante, "indice_unita": indice,
                    "generatore": GENERATORE, "seme": seme})

    # 1. sostenute: ogni turno col suo fatto
    for parlante, testo, claim in turni[:4]:
        aggiungi("sostenuta", _riga(parlante, testo), claim, claim, 1, 1)
    # 2. altro turno: la memoria unisce il fatto del turno 0 (A) e quello del turno 2 (A); la fonte è il turno 0
    (pa, ta, ca), (_, _, cb) = turni[0], turni[2]
    memoria = f"{ca.rstrip('.')}{t['coordinata']}{coda(cb, A)}."
    unita = unita_con_etichetta(memoria, [(ca, 1), (cb, 0)], A)
    for k, (u, e) in enumerate(unita):
        aggiungi("altro_turno" if e == 0 else "sostenuta", _riga(pa, ta), memoria, u, e, len(unita), k)
    # 3. parlante scambiato: il fatto del turno 1 (detto da B) attribuito ad A
    pb1, tb1, cb1 = turni[1]
    scambiato = A + cb1[len(pb1):] if cb1.startswith(pb1) else cb1
    aggiungi("parlante", _riga(pb1, tb1), scambiato, scambiato, 0, 1)
    # 4. la fonte nell'etichetta: il turno col pronome da solo non nomina l'evento, la finestra sì
    (p4, t4, _), (p5, t5, _), (p6, t6, c6) = turni[4], turni[5], turni[6]
    aggiungi("fonte_turno", _riga(p6, t6), c6, c6, 0, 1)
    finestra = "\n".join(_riga(p, x) for p, x in ((p4, t4), (p5, t5), (p6, t6)))
    aggiungi("fonte_finestra", finestra, c6, c6, 1, 1)
    return out


def genera(dialoghi: int, seme: int) -> list[dict]:
    """The rows of `dialoghi` dialogues per language, deterministic with the seed and checked by
    `controlla()`: what the command writes, and what a test reads without writing a file."""
    rng = random.Random(seme)
    righe = []
    for lingua in LINGUE:
        for n in range(dialoghi):
            righe.extend(coppie(dialogo(rng, lingua, n), seme))
    # the judge reads only the source and the claim: a pair repeated by two constructions (the first unit
    # of a split memory is the claim of its turn) or by two dialogues is one example, kept once
    righe = senza_coppie_ripetute(righe)
    controlla(righe)
    return righe


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--dialoghi", type=int, default=60, help="dialoghi per lingua")
    ap.add_argument("--seme", type=int, default=20260930)
    ap.add_argument("--uscita", required=True)
    ap.add_argument("--campione", type=int, default=0, help="righe prese a caso in un secondo file, da leggere")
    a = ap.parse_args(argv)
    import verimem
    print("verimem from:", verimem.__file__)
    righe = genera(a.dialoghi, a.seme)
    uscita = Path(a.uscita)
    uscita.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in righe), encoding="utf-8")
    import hashlib
    print(f"righe: {len(righe)} -> {uscita} · sha256 {hashlib.sha256(uscita.read_bytes()).hexdigest()}")
    print("per tipo e lingua:", dict(sorted(Counter((r['lingua'], r['tipo']) for r in righe).items())))
    print("etichette:", dict(Counter(r["etichetta"] for r in righe)))
    memorie = {(r["dialogo"], r["memoria"]): r["unita_nella_memoria"] for r in righe}
    print("memorie: intere", sum(v == 1 for v in memorie.values()), "· spezzate", sum(v > 1 for v in memorie.values()))
    if a.campione:
        camp = random.Random(a.seme + 1).sample(righe, min(a.campione, len(righe)))
        c = uscita.with_name(uscita.stem + "-campione.jsonl")
        c.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in camp), encoding="utf-8")
        print(f"campione: {len(camp)} -> {c}")
    return 0


