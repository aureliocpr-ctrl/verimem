CANONI = [640, 720, 850, 930, 1100, 1250]
GIORNI = [3, 7, 14, 21, 28]          # no value is a suffix of another: «7 May» is never inside «17 May»
DEPOSITI = [1, 2, 3]
POMPE_TOT = [8, 9, 10, 12]
POMPE_FERME = [2, 3, 5]
PRESSIONI = [4, 6, 8, 10]


def _codice(rng: random.Random, lettera: str) -> str:
    return f"{lettera}-{rng.randint(1000, 9999)}"


def _altro(rng: random.Random, scelte: list, fonte: str, formato=str, evita=None) -> object:
    """A value whose written form is NOT inside the source: the mark of a negative must be absent."""
    for _ in range(100):
        x = rng.choice(scelte)
        if x != evita and formato(x) not in fonte:
            return x
    raise ValueError(f"no value of {scelte} is absent from {fonte!r}")


def _righe_di(memoria_id: str, lingua: str, famiglia: str, fonte: str, memoria: str,
              atomici: list[tuple[str, int, str, str]], soggetto: str, seme: int) -> list[dict]:
    """`decomponi()` on the memory; every unit takes the atomic claim with the LOWEST label among those it
    contains (the gate's vote), with its type and mark. A unit with no known atomic claim stops the
    generator: it would be a pair whose label nobody wrote."""
    unita = decomponi(memoria)
    out = []
    for k, u in enumerate(unita):
        dentro = [a for a in atomici if coda(a[0], soggetto).lower() in u.lower()]
        assert dentro, f"unit with no known atomic claim: {u!r} from {memoria!r}"
        _, etichetta, tipo, segno = min(dentro, key=lambda a: a[1])
        out.append({"id": f"{memoria_id}-{k}", "lingua": lingua, "famiglia": famiglia, "tipo": tipo,
                    "fonte": fonte, "memoria": memoria, "claim": u, "etichetta": etichetta,
                    "unita_nella_memoria": len(unita), "indice_unita": k, "segno": segno,
                    "generatore": GENERATORE, "seme": seme})
    return out


def locazione(rng: random.Random, lingua: str, n: int, seme: int) -> list[dict]:
    t = LOCAZIONE[lingua]
    voci = {"id": _codice(rng, "LC"), "nome": rng.choice(t["nomi"]), "v": rng.choice(CANONI),
            "d": rng.choice(DEPOSITI), "g": rng.choice(GIORNI), "mese": rng.choice(t["mesi"])}
    # the language's own forms, not the cases avoided: «1 month» / «1 mes», and the Italian «ad»
    # before a word that starts with «a» («intestato ad Anna Neri»), found by Nadia on 2026-09-30
    deposito = lambda d: t["dep_uno" if d == 1 else "dep_piu"].format(d=d)  # noqa: E731
    voci["dep"] = deposito(voci["d"])
    voci["a_nome"] = ("ad " if voci["nome"][:1].lower() == "a" else "a ") + voci["nome"]
    fonte = t["fonte"].format(**voci)
    v2 = _altro(rng, CANONI, fonte, evita=voci["v"])
    data_di = lambda g: t["data"].format(g=g, mese=voci["mese"])  # noqa: E731
    g2 = _altro(rng, GIORNI, fonte, formato=data_di, evita=voci["g"])
    g3 = _altro(rng, GIORNI, fonte, formato=data_di, evita=g2)     # the split memory's own wrong date
    d2 = _altro(rng, DEPOSITI, fonte, formato=deposito, evita=voci["d"])
    id2 = _altro(rng, [_codice(rng, "LC") for _ in range(20)], fonte, evita=voci["id"])
    data, data2, data3 = data_di(voci["g"]), data_di(g2), data_di(g3)
    f = lambda chiave, **cambi: t[chiave].format(**{**voci, **cambi})  # noqa: E731
    atomici = {
        "sostenuta": (f("sostenuta"), 1, "sostenuta", str(voci["v"])),
        "parafrasi": (f("parafrasi"), 1, "parafrasi", str(voci["v"])),
        "tempo_vero": (f("tempo_vero"), 1, "sostenuta", data),
        "valore": (f("sostenuta", v=v2), 0, "valore", str(v2)),
        "entita": (f("sostenuta", id=id2), 0, "entita", id2),
        "negazione": (f("negazione"), 0, "negazione", t["segno_negazione"]),
        "tempo": (f("tempo_vero", g=g2), 0, "tempo", data2),
        "omissione": (f("omissione"), 0, "omissione", t["segno_omissione"]),
    }
    # the split memories get facts of their OWN: the judge reads (source, claim), and a unit that repeats a
    # whole memory is the same example written twice (960 of 4320 rows in d1_fonti@1, found by Nadia)
    proprie = {
        "deposito": (f("deposito"), 1, "sostenuta", voci["dep"]),
        "deposito_falso": (f("deposito", dep=deposito(d2)), 0, "valore", deposito(d2)),
        "intestatario": (f("intestatario"), 1, "sostenuta", voci["nome"]),
        "tempo_proprio": (f("tempo_vero", g=g3), 0, "tempo", data3),
    }
    soggetto = t["soggetto"].format(**voci)
    righe = []
    for nome, a in atomici.items():                               # whole memories: one atomic claim each
        # the other lease's claim has its own subject: it is matched against itself
        s = soggetto if nome != "entita" else t["soggetto"].format(id=id2)
        righe += _righe_di(f"{lingua}-loc{n:03d}-{nome}", lingua, "locazione", fonte, a[0], [a], s, seme)
    # split memories: two atomic claims, the second one joined by the coordinator with its verb first
    for nome, (primo, secondo) in {"deposito+tempo": ("deposito", "tempo_proprio"),
                                   "deposito_falso+intestatario": ("deposito_falso", "intestatario")}.items():
        a1, a2 = proprie[primo], proprie[secondo]
        memoria = f"{a1[0].rstrip('.')}{t['coordinata']}{coda(a2[0], soggetto)}."
        righe += _righe_di(f"{lingua}-loc{n:03d}-{nome}", lingua, "locazione", fonte, memoria, [a1, a2],
                           soggetto, seme)
    return righe


def impianto(rng: random.Random, lingua: str, n: int, seme: int) -> list[dict]:
    t = IMPIANTO[lingua]
    voci = {"id": _codice(rng, "PL"), "n": rng.choice(POMPE_TOT), "k": rng.choice(POMPE_FERME),
            "p": rng.choice(PRESSIONI)}
    fonte = t["fonte"].format(**voci)
    p2 = _altro(rng, PRESSIONI, fonte, formato=lambda p: f"{p} bar", evita=voci["p"])
    f = lambda chiave, **cambi: t[chiave].format(**{**voci, **cambi})  # noqa: E731
    atomici = {
        "sostenuta": (f("sostenuta"), 1, "sostenuta", str(voci["k"])),
        "parafrasi": (f("parafrasi"), 1, "parafrasi", str(voci["k"])),
        "pressione": (f("pressione"), 1, "sostenuta", f"{voci['p']} bar"),
        "valore": (f("pressione", p=p2), 0, "valore", f"{p2} bar"),
        "portata": (f("portata"), 0, "portata", t["segno_portata"]),
        "omissione": (f("omissione"), 0, "omissione", t["segno_omissione"]),
    }
    righe = []
    for nome, a in atomici.items():                               # whole memories only: the subjects differ
        righe += _righe_di(f"{lingua}-imp{n:03d}-{nome}", lingua, "impianto", fonte, a[0], [a], "", seme)
    return righe


def genera(seme: int, per_lingua: int) -> list[dict]:
    """All the rows, deterministic with the seed: `per_lingua` leases and plant sheets per language."""
    rng = random.Random(seme)
    righe = []
    for lingua in LOCAZIONE:
        for n in range(per_lingua):
            righe += locazione(rng, lingua, n, seme)
            righe += impianto(rng, lingua, n, seme)
    return righe


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--per-lingua", type=int, default=60)
    ap.add_argument("--seme", type=int, default=20260930)
    ap.add_argument("--uscita", required=True)
    ap.add_argument("--campione", type=int, default=0, help="rows drawn at random into a second file")
    a = ap.parse_args(argv)
    import verimem
    print("verimem from:", verimem.__file__)
    righe = genera(a.seme, a.per_lingua)
    controlla(righe)
    uscita = Path(a.uscita)
    uscita.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in righe), encoding="utf-8")
    print(f"rows: {len(righe)} -> {uscita} · sha256 {hashlib.sha256(uscita.read_bytes()).hexdigest()}")
    print("by language and type:", dict(sorted(Counter((r["lingua"], r["tipo"]) for r in righe).items())))
    print("labels:", dict(Counter(r["etichetta"] for r in righe)))
    memorie = {(r["fonte"], r["memoria"]): r["unita_nella_memoria"] for r in righe}
    print("memories: whole", sum(v == 1 for v in memorie.values()), "· split", sum(v > 1 for v in memorie.values()))
    if a.campione:
        camp = random.Random(a.seme + 1).sample(righe, min(a.campione, len(righe)))
        c = uscita.with_name(uscita.stem + "-campione.jsonl")
        c.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in camp), encoding="utf-8")
        print(f"sample: {len(camp)} -> {c}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
