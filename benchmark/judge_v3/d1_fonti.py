"""D1 for the v3 judge, the DOCUMENT part: constructed negatives on sources that are not dialogues.

The dialogue part (`d1_dialoghi.py`) builds pairs on synthetic conversations; this one builds them on
synthetic documents: a lease and a plant sheet, in English, Italian, French and Spanish. Same method:
every memory is made of atomic claims whose label the generator knows, `decomponi()` turns it into the
units the gate will ask about, and every unit takes the label of the weakest atomic claim it contains.

No model and no external data: ids, names, values and sentences are templates written here.
Deterministic with the seed.

Pair types (field `tipo`), with the mark (field `segno`) that makes the label true by construction:
  sostenuta   a fact of the document, in its words                     the value, in the source   label 1
  parafrasi   the same fact with a small inference that holds for        the value, in the source   label 1
              every value of its slots («rent of X a month» -> «costs X a month»)
  valore      the fact with another number                               the number, NOT in source   label 0
  entita      the fact given to another lease                            the other id, NOT in source label 0
  negazione   the fact denied                                            the negation word           label 0
  portata     «k of the n pumps» said of all of them                     «all», NOT in the source     label 0
  tempo       the fact with another date                                 the date, NOT in the source  label 0
  omissione   the fact with a detail the document does not give          the detail, NOT in source    label 0

Memories are whole (one atomic claim) or split (two, joined by the language's coordinator, so that
`decomponi()` returns two units with the inherited subject). Negations stay whole: «X does not ...» as
the first piece would make «X does not» the inherited subject.

The rows go through `d1_campi.controlla()` before they are written; the fields are the ones every D1
builder writes, plus `famiglia` and `segno`.

Run from the root of the checkout, with the `verimem` of this checkout:
    python benchmark/judge_v3/d1_fonti.py --per-lingua 60 --seme 20260930 \
        --uscita benchmark/judge_v3/d1-fonti.jsonl --campione 200
The full jsonl is regenerated by the script and not committed; its sha256 goes in the data card.
"""
